#!/usr/bin/env node

import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const outputPaths = {
  web: 'web/design-tokens.css',
  android: 'android/app/src/main/java/app/bookstr/ui/theme/Color.kt',
  swift: 'ios/BookstrIOS/Sources/Shared/Theme.swift',
};

const hexColor = /^#[0-9A-Fa-f]{6}$/;

function requireArray(value, label) {
  if (!Array.isArray(value) || value.length === 0) throw new Error(`${label} must be a non-empty array`);
}

function requireHex(value, label) {
  if (typeof value !== 'string' || !hexColor.test(value)) throw new Error(`${label} must be a six-digit hex color`);
}

export function validateTokens(tokens) {
  if (!tokens || tokens.version !== 1 || !tokens.web || !tokens.android || !tokens.swift || typeof tokens.web !== 'object' || typeof tokens.android !== 'object' || typeof tokens.swift !== 'object') {
    throw new Error('Design tokens must have version 1 and web, android, and swift sections');
  }
  if (!tokens.web.root || typeof tokens.web.root.colorScheme !== 'string') throw new Error('Web tokens must include a root color scheme');
  requireArray(tokens.web.themes, 'Web themes');
  for (const theme of tokens.web.themes) {
    if (typeof theme.selector !== 'string' || !theme.selector.startsWith('body.')) throw new Error('Web theme selector must target body');
    if (!theme.variables || typeof theme.variables !== 'object' || Array.isArray(theme.variables) || Object.keys(theme.variables).length === 0) throw new Error(`Web theme ${theme.selector} must include variables`);
    if (theme.colorScheme !== undefined && !['light', 'dark'].includes(theme.colorScheme)) throw new Error(`Web theme ${theme.selector} has an invalid color scheme`);
    for (const [name, value] of Object.entries(theme.variables)) {
      if (!/^[a-z][a-z0-9-]*$/.test(name) || typeof value !== 'string' || value.length === 0) throw new Error(`Web theme ${theme.selector} has an invalid variable`);
    }
  }
  requireArray(tokens.android.colors, 'Android colors');
  const androidNames = new Set();
  for (const color of tokens.android.colors) {
    if (!color || !/^[A-Z][A-Za-z0-9]*$/.test(color.name) || androidNames.has(color.name)) throw new Error('Android colors must have unique Kotlin names');
    if ((color.value === undefined) === (color.alias === undefined)) throw new Error(`Android color ${color.name} must have exactly one value or alias`);
    if (color.value !== undefined) requireHex(color.value, `Android color ${color.name}`);
    if (color.alias !== undefined && (typeof color.alias !== 'string' || !androidNames.has(color.alias))) throw new Error(`Android color ${color.name} must alias an earlier color`);
    androidNames.add(color.name);
  }
  requireArray(tokens.swift.colors, 'Swift colors');
  for (const color of tokens.swift.colors) {
    if (!color || !/^[a-z][A-Za-z0-9]*$/.test(color.name)) throw new Error('Swift colors must have lower-camel-case names');
    requireHex(color.value, `Swift color ${color.name}`);
  }
  requireArray(tokens.swift.readerThemes, 'Swift reader themes');
  const swiftNames = new Set(tokens.swift.colors.map((color) => color.name));
  const themeNames = new Set();
  for (const theme of tokens.swift.readerThemes) {
    if (!theme || !['white', 'paper', 'night'].includes(theme.name) || themeNames.has(theme.name)) throw new Error('Swift reader themes must include white, paper, and night once');
    requireHex(theme.background, `Swift reader theme ${theme.name}`);
    if (!swiftNames.has(theme.primary)) throw new Error(`Swift reader theme ${theme.name} must reference a Swift color`);
    themeNames.add(theme.name);
  }
  if (themeNames.size !== 3) throw new Error('Swift reader themes must include white, paper, and night once');
  return tokens;
}

function rgb(hex) {
  return [hex.slice(1, 3), hex.slice(3, 5), hex.slice(5, 7)].map((value) => Number.parseInt(value, 16));
}

function swiftColor(hex) {
  const [red, green, blue] = rgb(hex);
  const component = (value) => value === 255 ? '1' : `${value} / 255`;
  return `Color(red: ${component(red)}, green: ${component(green)}, blue: ${component(blue)})`;
}

export function renderWeb(tokens) {
  validateTokens(tokens);
  const root = `:root {\n  color-scheme: ${tokens.web.root.colorScheme};\n}`;
  const themes = tokens.web.themes.map((theme) => {
    const scheme = theme.colorScheme ? `\n  color-scheme: ${theme.colorScheme};` : '';
    const variables = Object.entries(theme.variables).map(([name, value]) => `  --${name}: ${value};`).join('\n');
    return `${theme.selector} {${scheme}\n${variables}\n}`;
  });
  return `/* Generated by shared/design-tokens/generate.mjs. Do not edit directly. */\n\n${[root, ...themes].join('\n\n')}\n`;
}

export function renderAndroid(tokens) {
  validateTokens(tokens);
  const colors = tokens.android.colors.map((color) => `val ${color.name} = ${color.alias || `Color(0xFF${color.value.slice(1)})`}`).join('\n');
  return `// Generated by shared/design-tokens/generate.mjs. Do not edit directly.\npackage app.bookstr.ui.theme\n\nimport androidx.compose.ui.graphics.Color\n\n${colors}\n`;
}

export function renderSwift(tokens) {
  validateTokens(tokens);
  const staticColors = tokens.swift.colors.map((color) => `    static let ${color.name} = ${swiftColor(color.value)}`).join('\n');
  const backgroundCases = tokens.swift.readerThemes.map((theme) => `        case .${theme.name}: return ${swiftColor(theme.background)}`).join('\n');
  const primaryCases = tokens.swift.readerThemes.map((theme) => `        case .${theme.name}: return .${theme.primary}`).join('\n');
  return `// Generated by shared/design-tokens/generate.mjs. Do not edit directly.\nimport SwiftUI\nimport UIKit\n\nextension Color {\n${staticColors}\n}\n\nextension ReaderTheme {\n    var colorScheme: ColorScheme {\n        self == .night ? .dark : .light\n    }\n\n    var background: Color {\n        switch self {\n${backgroundCases}\n        }\n    }\n\n    var uiBackground: UIColor {\n        UIColor(background)\n    }\n\n    var primary: Color {\n        switch self {\n${primaryCases}\n        }\n    }\n}\n`;
}

export function renderOutputs(tokens) {
  return {
    [outputPaths.web]: renderWeb(tokens),
    [outputPaths.android]: renderAndroid(tokens),
    [outputPaths.swift]: renderSwift(tokens),
  };
}

export function parseArgs(args) {
  const options = { check: false, input: 'shared/design-tokens/tokens.json' };
  for (const argument of args) {
    if (argument === '--check') options.check = true;
    else if (argument.startsWith('--input=')) options.input = argument.slice('--input='.length);
    else throw new Error(`Unknown argument: ${argument}`);
  }
  if (!options.input) throw new Error('--input requires a path');
  return options;
}

export async function run(args, io = { readFile, writeFile }, cwd = process.cwd()) {
  const options = parseArgs(args);
  const tokens = JSON.parse(await io.readFile(resolve(cwd, options.input), 'utf8'));
  const outputs = renderOutputs(tokens);
  const stale = [];
  for (const [path, generated] of Object.entries(outputs)) {
    const output = resolve(cwd, path);
    if (options.check) {
      const current = await io.readFile(output, 'utf8').catch(() => '');
      if (current !== generated) stale.push(path);
    } else {
      await io.writeFile(output, generated);
    }
  }
  if (stale.length > 0) throw new Error(`Generated design tokens are stale: ${stale.join(', ')}`);
  return options.check ? 'checked' : 'generated';
}

export async function cli(args, services = {}) {
  const execute = services.run || run;
  const writeError = services.writeError || ((message) => process.stderr.write(message));
  const fail = services.fail || (() => { process.exitCode = 1; });
  try {
    return await execute(args);
  } catch (error) {
    writeError(`${error.message}\n`);
    fail();
    return 'failed';
  }
}

export function invokeIfMain(moduleUrl, argv, action = cli) {
  const invokedPath = argv[1] ? pathToFileURL(resolve(argv[1])).href : '';
  return moduleUrl === invokedPath ? action(argv.slice(2)) : Promise.resolve('imported');
}

await invokeIfMain(import.meta.url, process.argv);
