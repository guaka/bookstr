#!/usr/bin/env node

import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const fields = ['id', 'label', 'shell', 'reader', 'speech', 'catalog', 'persistence', 'sharedCore'];

export function validateInventory(inventory) {
  if (!inventory || inventory.version !== 1 || !Array.isArray(inventory.clients)) {
    throw new Error('Client inventory must have version 1 and a clients array');
  }
  if (inventory.clients.length !== 4) {
    throw new Error('Client inventory must describe exactly four clients');
  }

  const ids = new Set();
  for (const client of inventory.clients) {
    for (const field of fields) {
      if (typeof client[field] !== 'string' || client[field].trim() === '') {
        throw new Error(`Client ${client.id || '<unknown>'} is missing ${field}`);
      }
    }
    if (ids.has(client.id)) throw new Error(`Duplicate client id: ${client.id}`);
    ids.add(client.id);
  }

  const expected = ['web', 'electron', 'android', 'ios'];
  if (expected.some((id) => !ids.has(id))) {
    throw new Error(`Client inventory must include ${expected.join(', ')}`);
  }
  return inventory;
}

function cell(value) {
  return value.replaceAll('|', '\\|').replaceAll(/\s+/g, ' ').trim();
}

export function renderOverview(inventory) {
  validateInventory(inventory);
  const rows = inventory.clients.map((client) =>
    [
      client.label,
      client.shell,
      client.reader,
      client.speech,
      client.catalog,
      client.persistence,
      client.sharedCore,
    ].map(cell).join(' | '),
  );

  return `# Bookstr client capability matrix

<!-- Generated by scripts/generate-client-overview.mjs. Do not edit directly. -->

The four clients share contracts and deterministic behavior while retaining
their native shells and platform integrations. See
[CLIENT_ARCHITECTURE.md](CLIENT_ARCHITECTURE.md) for the ownership boundary.

Client | Shell | Reader | Speech playback | Catalog adapter | Persistence | Shared-core consumption
--- | --- | --- | --- | --- | --- | ---
${rows.join('\n')}

The source of truth is \`shared/architecture/clients.json\`. Run
\`node scripts/generate-client-overview.mjs --check\` to detect stale output.
`;
}

export function parseArgs(args) {
  const options = {
    check: false,
    input: 'shared/architecture/clients.json',
    output: 'docs/CLIENT_CAPABILITIES.md',
  };
  for (let index = 0; index < args.length; index += 1) {
    const argument = args[index];
    if (argument === '--check') {
      options.check = true;
    } else if (argument === '--input' || argument === '--output') {
      const value = args[index + 1];
      if (!value || value.startsWith('--')) throw new Error(`${argument} requires a path`);
      options[argument.slice(2)] = value;
      index += 1;
    } else {
      throw new Error(`Unknown argument: ${argument}`);
    }
  }
  return options;
}

export async function run(args, io = { readFile, writeFile }, cwd = process.cwd()) {
  const options = parseArgs(args);
  const input = resolve(cwd, options.input);
  const output = resolve(cwd, options.output);
  const inventory = JSON.parse(await io.readFile(input, 'utf8'));
  const generated = renderOverview(inventory);

  if (options.check) {
    const current = await io.readFile(output, 'utf8').catch(() => '');
    if (current !== generated) throw new Error(`${options.output} is stale; regenerate it`);
    return 'checked';
  }

  await io.writeFile(output, generated);
  return 'generated';
}

export async function cli(args, services = {}) {
  const execute = services.run || run;
  const writeError = services.writeError || ((message) => process.stderr.write(message));
  const fail = services.fail || (() => { process.exitCode = 1; });
  try {
    return await execute(args);
  } catch (error) {
    writeError(`${error.message}\n`);
    fail();
    return 'failed';
  }
}

export function invokeIfMain(moduleUrl, argv, action = cli) {
  const invokedPath = argv[1] ? pathToFileURL(resolve(argv[1])).href : '';
  return moduleUrl === invokedPath ? action(argv.slice(2)) : Promise.resolve('imported');
}

await invokeIfMain(import.meta.url, process.argv);
